def _expand_requests() -> list[str]:
    verbs = ["оформи доступ к", "нужен доступ к", "запроси доступ к", "хочу доступ к"]
    out = []
    for verb, res, lvl, reason in product(verbs, _RESOURCES[:6], _LEVELS[:4], _REASONS):
        out.append(" ".join(x for x in (verb, res, lvl, reason) if x))
    # детерминированная подвыборка, чтобы не перекосить классы
    return out[::17]


def training_set() -> tuple[list[str], list[str]]:
    texts, labels = [], []
    for intent, examples in DATA.items():
        for t in examples:
            texts.append(t)
            labels.append(intent)
    for t in _expand_requests():
        texts.append(t)
        labels.append("request_access")
    return texts, labels
