import { resources } from './catalog.mjs';

const resourceAliases = [
  /(?:баз[а-я]*\s+знаний|пространств[а-я]*|документаци[а-я]*|вики|wiki)/gu,
  /(?:учебн[а-я]*\s+)?(?:git[- ]?)?(?:репозитор[а-я]*|песочниц[а-я]*)|auto core/gu,
  /goods search|поиск[а-я]* товаров/gu,
  /auto backend|авто бэкенд/gu,
  /промышленн[а-я]*\s+(?:баз[а-я]*\s+данных|бд)|prod|fintech|финтех/gu,
];
const vocabulary = [
  /я|мне|моя|мы|наш[а-я]*|сво[а-я]*|мо[ейяюих]+|ваш[а-я]*|эт[а-я]*|его|ее|их|ты|вы/,
  /а|и|или|в|во|на|по|к|ко|с|со|из|у|от|до|для|за|о|об|без|про|через|ли|чем|еще|только|сначала|пожалуйста|привет|здравствуй(?:те)?/,
  /как|како[а-я]*|каки[а-я]*|кака[а-я]*|где|что|кто|сколько|когда|куда|пока|долго|почему/,
  /можно|может|могу|надо|нуж[а-я]*|хочу|хотел[аи]?|хотелось|бы|требуется|будет|есть|делать/,
  /помог[аи][а-я]*|подскаж[а-я]*|расскаж[а-я]*|объясни[а-я]*|покажи[а-я]*|пожалуйст[а-я]*|дайте|дай|выдай|сделай|меня/,
  /доступ[а-я]*|заявк[а-я]*|заявок|запрос[а-я]*|запрашива[а-я]*|получ[а-я]*|оформ[а-я]*|подать|пода[чю][а-я]*|отправ[а-я]*|попасть|открыть|зайти/,
  /прав[а-я]*|поряд[а-я]*|процедур[а-я]*|шаг[а-я]*|ресурс[а-я]*|команд[а-я]*|корпоративн[а-я]*|учебн[а-я]*|стажер[а-я]*|сотрудник[а-я]*|перв[а-я]*|недел[а-я]*|адаптаци[а-я]*/,
  /уров[а-я]*|уровн[а-я]*|чтени[а-я]*|читать|чтение|запис[а-я]*|редактир[а-я]*|read|write|разниц[а-я]*|отлич[а-я]*/,
  /соглас[а-я]*|рассмотр[а-я]*|срок[а-я]*|ждать|жду|ждут|ожида[а-я]*|руководител[а-я]*|тимлид[а-я]*|наставник[а-я]*|занима[а-я]*|прид[её]т/,
  /ограничени[а-я]*|безопасност[а-я]*|админ[а-я]*|квот[а-я]*|квартал[а-я]*|лицензи[а-я]*|закрыт[а-я]*|чек[- ]?лист[а-я]*/,
];
const knownWord = new RegExp(
  '^(?:' + vocabulary.map((r) => r.source).join('|') + ')$',
  'u',
);
const questionStart =
  /^(?:(?:а|и|подскажите|пожалуйста)[, ]+)*(?:как|како|каки|кака|кто|что|где|зачем|почему|когда|куда|сколько|можно ли|подскажи)/u;
const purpose =
  /^(?:изучи[а-я]*|изучени[а-я]*|прохож[а-я]*|пройти|прочитать|вести|ведения|подготов[а-я]*|разобраться|ознаком[а-я]*|работ[а-я]*|провер[а-я]*|обнов[а-я]*|добавить|выполн[а-я]*|написать|исправить|сверить|тестир[а-я]*)(?:\s|$)/u;
export function requestSubject(text) {
  const intro =
    /(?:^|\s)(для|чтобы|причина\s*[:—]|обоснование\s*[:—])\s+/u.exec(text);
  if (
    !intro ||
    intro.index === 0 ||
    text.includes('?') ||
    questionStart.test(text)
  )
    return text;
  const rest = text.slice(intro.index + intro[0].length);
  return intro[1] !== 'для' || purpose.test(rest)
    ? text.slice(0, intro.index)
    : text;
}
export function classifyScope(text, previous) {
  const question = text.includes('?') || questionStart.test(text);
  const intro =
    /(?:^|\s)(?:для|чтобы|причина\s*[:—]|обоснование\s*[:—])\s+/u.exec(text);
  const expectsReason =
    previous?.resource_id && previous.access_level && !previous.justification;
  if (expectsReason && !question && (purpose.test(text) || intro?.index === 0))
    return 'reason';
  let subject = requestSubject(text);
  for (const resource of resources)
    subject = subject.replaceAll(resource.id, ' ');
  for (const alias of resourceAliases) subject = subject.replace(alias, ' ');
  const words = subject.match(/[\p{L}\p{N}_]+/gu) || [];
  return words.every((word) => knownWord.test(word)) ? 'procedure' : 'unknown';
}
